import * as fs from "node:fs/promises";
import { editAutoGeneratedMessage } from "@oh-my-pi/pi-natives";
import { settings as globalSettings, isSettingsInitialized, type Settings } from "../config/settings";
import type { FilesystemOperation } from "../internal/session-path-scope";

import { ToolError } from "@oh-my-pi/pi-tui/tools/tool-errors";
import { cfgEditBlockAutoGenerated } from "../edit/settings";

function shouldBlockAutoGeneratedFiles(activeSettings?: Settings): boolean {
	if (activeSettings) return cfgEditBlockAutoGenerated.get(activeSettings);
	if (isSettingsInitialized()) return cfgEditBlockAutoGenerated.get(globalSettings);
	return cfgEditBlockAutoGenerated.default;
}

function exactNativeContentPath(fd: number): string {
	if (process.platform !== "linux") {
		throw new Error("Exact generated-header reads require Linux /proc/self/fd support.");
	}
	return `/proc/self/fd/${fd}`;
}

/** Throw when the native generated-file detector rejects this path. */
export async function assertEditableFile(
	absolutePath: string,
	displayPath?: string,
	activeSettings?: Settings,
	operation?: FilesystemOperation,
): Promise<void> {
	if (!shouldBlockAutoGeneratedFiles(activeSettings)) return;
	if (!operation) {
		const message = editAutoGeneratedMessage(absolutePath, displayPath ?? absolutePath);
		if (message) throw new ToolError(message);
		return;
	}
	const target = await operation.authorize(absolutePath, "read");
	const handle = await operation.openRead(target);
	try {
		const nativePath = exactNativeContentPath(handle.fd);
		const sourceIdentity = await fs.stat(nativePath, { bigint: true }).catch(cause => {
			throw new Error("Exact generated-header reads require accessible Linux /proc/self/fd support.", { cause });
		});
		const admittedIdentity = await handle.stat({ bigint: true });
		if (sourceIdentity.dev !== admittedIdentity.dev || sourceIdentity.ino !== admittedIdentity.ino) {
			throw new Error("Native generated-header source does not match the admitted file.");
		}
		const message = editAutoGeneratedMessage(nativePath, displayPath ?? absolutePath);
		if (message) throw new ToolError(message);
	} finally {
		await handle.close();
	}
}
